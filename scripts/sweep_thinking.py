"""Run one cell per thinking mode, back to back, in one command.

Thinking mode is a server setting, so each mode gets its own vLLM launch:

    for each mode:  write the cell config -> restart vLLM from it -> wait ready
                    -> run the harness into its own directory
    then:           export every mode into one CSV

Each mode is a separate cell with its own config_id, and the generated configs
are saved beside the results, so the sweep is reproducible from its output
directory alone.

    python scripts/sweep_thinking.py --base-config configs/pilot_qwen.yaml \\
        --tasks dataset/tasks/phase1.json --modes off,low,medium,xhigh \\
        --repeats 3 --limit 15

Modes: "off"; "on" for a model with thinking but no effort levels (Nemotron);
or an effort the model's template accepts (Qwen3.8: low, medium, xhigh). A model
without thinking (Llama 3) runs "off" only. The sweep stops at the first mode that fails, rather than producing a
partial result that looks complete.
"""

from __future__ import annotations

import argparse
import datetime as dt
import os
import subprocess
import sys
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PY = str(ROOT / ".venv/bin/python")


def sh(cmd: list[str], log: Path | None = None, check: bool = True) -> int:
    print(f"$ {' '.join(cmd)}", flush=True)
    if log is None:
        return subprocess.run(cmd, cwd=ROOT, check=check).returncode
    with open(log, "w") as fh:
        return subprocess.run(cmd, cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT, check=check).returncode


def harness_running() -> bool:
    out = subprocess.run(["pgrep", "-af", "agent.harness.cli"], capture_output=True, text=True).stdout
    return any("pgrep" not in line for line in out.splitlines())


LOCK = ROOT / "output" / ".sweep.lock"


def acquire_lock(out_root: Path, modes: list[str], config: str) -> None:
    """One sweep at a time, enforced with a PID lock file.

    Another sweep would stop vLLM out from under this one mid-restart, when no
    harness is running. Matching process command lines was unreliable: the
    shell that launches a sweep carries "sweep_thinking.py" in its own command
    line and looked like a second sweep. A lock holding a live PID does not.
    """
    import atexit
    import json

    if LOCK.exists():
        try:
            held = json.loads(LOCK.read_text())
            os.kill(int(held["pid"]), 0)  # raises if that process is gone
            raise SystemExit(
                f"another sweep is running (pid {held['pid']}, {held.get('config')}); "
                "see ./scripts/status.sh"
            )
        except (ProcessLookupError, ValueError, KeyError, json.JSONDecodeError):
            pass  # stale lock from a sweep that died; take it over
    LOCK.parent.mkdir(parents=True, exist_ok=True)
    LOCK.write_text(json.dumps({
        "pid": os.getpid(), "config": config, "modes": modes, "out_root": str(out_root),
    }))

    def release() -> None:
        try:
            if json.loads(LOCK.read_text()).get("pid") == os.getpid():
                LOCK.unlink()
        except Exception:
            pass

    atexit.register(release)


def write_cell_config(base: dict, mode: str, path: Path) -> None:
    cell = yaml.safe_load(yaml.safe_dump(base))  # deep copy
    if mode == "off":
        cell["model"]["thinking_setting"] = "off"
        cell["model"]["reasoning_effort"] = ""
    elif mode == "on":
        # For a model whose template has thinking on/off but no effort levels.
        cell["model"]["thinking_setting"] = "on"
        cell["model"]["reasoning_effort"] = ""
    else:
        cell["model"]["thinking_setting"] = "on"
        cell["model"]["reasoning_effort"] = mode
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"# Generated by sweep_thinking.py for mode '{mode}'.\n"
        + yaml.safe_dump(cell, sort_keys=False)
    )


def validate(path: Path) -> None:
    """Fail on a bad mode before stopping the running server."""
    rc = subprocess.run([PY, "scripts/serve_args.py", str(path)], cwd=ROOT,
                        capture_output=True, text=True)
    if rc.returncode != 0:
        raise SystemExit(f"{path.name}: {rc.stderr.strip()}")


def serve(config: Path, log: Path) -> None:
    sh(["./scripts/stop_vllm.sh"], check=False)
    print(f"starting vLLM from {config.name} (log: {log})", flush=True)
    with open(log, "w") as fh:
        subprocess.Popen(
            ["./scripts/serve_vllm.sh", "--config", str(config)],
            cwd=ROOT, stdout=fh, stderr=subprocess.STDOUT, start_new_session=True,
        )
    rc = subprocess.run(["./scripts/wait_ready.sh"], cwd=ROOT,
                        env={**os.environ, "LOG": str(log)}).returncode
    if rc != 0:
        raise SystemExit(f"vLLM did not start for {config.name}; see {log}")


def ensure_proxy() -> None:
    rc = subprocess.run(["curl", "-s", "--max-time", "3",
                         "http://127.0.0.1:8100/control/health"],
                        capture_output=True).returncode
    if rc != 0:
        sh(["./scripts/start_stack.sh"])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base-config", required=True)
    ap.add_argument("--tasks", required=True)
    ap.add_argument("--modes", default="off,low,medium,xhigh")
    ap.add_argument("--frameworks", default="langgraph")
    ap.add_argument("--repeats", type=int, default=3)
    ap.add_argument("--limit", type=int, default=0,
                    help="sample N tasks across task types; 0 = every task (default)")
    ap.add_argument("--out-root", default="")
    ap.add_argument("--run-code", default="",
                    help="label recorded on every run of every mode (passed to the harness)")
    ap.add_argument("--tool-mode", choices=["replay", "record"], default="replay",
                    help="'record' makes this a probe sweep: new web/FRED queries are fetched "
                         "live and saved as fixtures. Probe results are not for analysis.")
    ap.add_argument("--dry-run", action="store_true",
                    help="write and validate the mode configs, print the plan, touch nothing")
    args = ap.parse_args()

    if harness_running():
        raise SystemExit("a harness is already running; wait for it (./scripts/status.sh)")

    modes = [m.strip() for m in args.modes.split(",") if m.strip()]
    stamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    base = yaml.safe_load((ROOT / args.base_config).read_text())
    model_dir = base["model"].get("local_dir") or base["model"]["repo"].split("/")[-1]
    kind = "probe" if args.tool_mode == "record" else "thinking_sweep"
    out_root = ROOT / (args.out_root or f"output/runs/{kind}_{model_dir}_{stamp}")
    if out_root.exists() and any(out_root.iterdir()):
        raise SystemExit(f"{out_root} is not empty; pick a new --out-root")

    # Write and validate every mode first, so a typo in the last mode is caught
    # before the first restart rather than an hour in.
    configs = {}
    for mode in modes:
        path = out_root / "configs" / f"{mode}.yaml"
        write_cell_config(base, mode, path)
        validate(path)
        configs[mode] = path
    print(f"sweep: {modes} -> {out_root}\n", flush=True)
    if args.dry_run:
        for mode, path in configs.items():
            m = yaml.safe_load(path.read_text())["model"]
            print(f"  {mode:7s} thinking={m['thinking_setting']:3s} "
                  f"effort={m['reasoning_effort'] or '-':6s} -> {out_root / mode}")
        import json
        n_tasks = len(json.loads((ROOT / args.tasks).read_text()))
        n = min(args.limit, n_tasks) if args.limit else n_tasks
        runs = n * args.repeats * len(args.frameworks.split(","))
        print(f"\n{len(modes)} restarts, {runs} runs per mode, {runs * len(modes)} runs total")
        print("dry run: configs written and validated; server untouched")
        return 0

    acquire_lock(out_root, modes, args.base_config)
    started = time.time()
    for i, mode in enumerate(modes, 1):
        t0 = time.time()
        print(f"\n===== [{i}/{len(modes)}] thinking={mode} =====", flush=True)
        serve(configs[mode], out_root / f"vllm_{mode}.log")
        ensure_proxy()
        rc = sh([
            PY, "-m", "agent.harness.cli",
            "--config", str(configs[mode]),
            "--tasks", args.tasks,
            "--frameworks", args.frameworks,
            "--repeats", str(args.repeats),
            "--limit", str(args.limit),
            "--out", str(out_root / mode),
            "--no-timestamp",  # the sweep root is already timestamped
            "--tool-mode", args.tool_mode,
            "--run-code", args.run_code,
        ], log=out_root / f"harness_{mode}.log", check=False)
        if rc != 0:
            raise SystemExit(f"harness failed for mode {mode}; see {out_root}/harness_{mode}.log")
        print(f"mode {mode} done in {(time.time() - t0) / 60:.1f} min", flush=True)

    print(f"\n===== export =====", flush=True)
    sh([PY, "scripts/export_csv.py",
        "--runs", *[str(out_root / m) for m in modes],
        "--out", str(out_root / "results.csv"), "--calls", "--no-timestamp"])
    print(f"\nsweep finished in {(time.time() - started) / 60:.1f} min -> {out_root}/results.csv")
    print(f"vLLM is still serving the last mode ({modes[-1]}); "
          "preflight will catch it if the next run expects another")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
