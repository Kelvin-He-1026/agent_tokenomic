"""Write a variant of a cell config with a different tensor-parallel size.

TP is a serving setting, and the config is the single source for how a model
is served: serve_vllm.sh launches from it, preflight checks the running server
against it, and tp_size is part of the cell's config_id. So a TP variant is
its own config file rather than a flag that could drift from the record.

    python scripts/make_cell.py --base configs/pilot_qwen.yaml --tp-size 2
    # -> configs/pilot_qwen_tp2.yaml; serve, run and sweep it like any other cell

The two GPUs here sit on different sockets with no NVLink, so every layer's
all-reduce crosses PCIe and the socket link. At one request at a time decoding
is bound by memory bandwidth, which TP=2 doubles; a first check on Qwen3.8-27B
was about 1.8x faster per token. A TP=2 cell uses both GPUs, so it runs with no
stack (ATK_STACK unset) and nothing else alongside.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from agent.config import RunConfig  # noqa: E402


def gpu_count() -> int:
    out = subprocess.run(["nvidia-smi", "--query-gpu=index", "--format=csv,noheader"],
                         capture_output=True, text=True).stdout
    return len([line for line in out.splitlines() if line.strip()])


def check_divisible(model_dir: Path, tp: int) -> list[str]:
    """Head counts vLLM must split evenly across TP ranks."""
    cfg_path = model_dir / "config.json"
    if not cfg_path.exists():
        return [f"cannot check head counts: {cfg_path} missing"]
    cfg = json.loads(cfg_path.read_text())
    cfg = cfg.get("text_config", cfg)
    problems = []
    for key in ("num_attention_heads", "mamba_num_heads"):
        n = cfg.get(key)
        if n and n % tp:
            problems.append(f"{key}={n} is not divisible by tp_size={tp}")
    kv = cfg.get("num_key_value_heads")
    if kv and tp > kv:
        problems.append(f"num_key_value_heads={kv} < tp_size={tp}: KV heads would be replicated")
    elif kv and kv % tp:
        problems.append(f"num_key_value_heads={kv} is not divisible by tp_size={tp}")
    return problems


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True, help="cell config to copy")
    ap.add_argument("--tp-size", type=int, required=True)
    ap.add_argument("--max-model-len", type=int, default=0,
                    help="also set model.max_model_len (context window); thinking runs with a "
                         "large output cap need prompt + max_tokens to fit")
    ap.add_argument("--out", default="", help="default: <base>_tp<N>.yaml beside the base")
    args = ap.parse_args()

    base_path = ROOT / args.base
    raw = yaml.safe_load(base_path.read_text())
    if args.tp_size < 1:
        raise SystemExit("--tp-size must be at least 1")
    if args.tp_size > gpu_count():
        raise SystemExit(f"tp_size={args.tp_size} but this machine has {gpu_count()} GPU(s)")

    raw["model"]["tp_size"] = args.tp_size
    if args.max_model_len:
        raw["model"]["max_model_len"] = args.max_model_len
    stem = base_path.stem
    for suffix in (f"_tp{n}" for n in range(1, 9)):
        stem = stem.removesuffix(suffix)
    out = ROOT / (args.out or f"{base_path.parent.relative_to(ROOT)}/{stem}_tp{args.tp_size}.yaml")

    extra = f", max_model_len={args.max_model_len}" if args.max_model_len else ""
    header = (f"# Generated by scripts/make_cell.py from {args.base}: tp_size={args.tp_size}{extra}.\n"
              "# A separate cell (its own config_id). With tp_size > 1 it needs every GPU,\n"
              "# so serve it with ATK_STACK unset and run nothing alongside it.\n")
    out.write_text(header + yaml.safe_dump(raw, sort_keys=False))

    cfg = RunConfig.from_yaml(out)  # same validation as a run
    for p in check_divisible(cfg.resolve(cfg.models_dir) / cfg.model.local_dir, args.tp_size):
        print(f"warning: {p}")
    print(f"wrote {out.relative_to(ROOT)}  ({cfg.model.served_name}, tp_size={cfg.model.tp_size})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
